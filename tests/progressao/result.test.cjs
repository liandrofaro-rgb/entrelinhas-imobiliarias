const assert=require('node:assert/strict');
const {createApp}=require('./harness.cjs');
const cases=require('./cases.cjs');
const eliz=cases.find(c=>c.name.startsWith('Elizangela')).input;
let checks=0;
function check(value,why){assert.ok(value,why);checks++;}
function render(changes={},input=eliz){const app=createApp();app.fill({...input,...changes});app.run();return app;}
function text(app,id){return app.$(id).textContent;}
let app=render();
check(text(app,'fa-result-heading')==='Há possíveis progressões a revisar.','Conclusion identifies a difference without promising an award');
check(text(app,'fa-qualifier').includes('tempo de serviço e pela formação'),'Both reasons for review are explicit');
check(text(app,'fa-gain-value')==='4,04%','Elizangela combined factor stays 4.0375%, rounded');
check(text(app,'fa-gain-note').includes('não sobre o total'),'Denominator is explained');
check(!text(app,'fa-horizontal-current-percent').includes('0%'),'Initial level does not suggest zero pay');
check(text(app,'fa-result-note').includes('17/07/2010'),'Reference date stays available');
const order=app.root.descendants().map(e=>e.id);
check(order.indexOf('fa-pccr-result')<order.indexOf('fa-gain'),'Comparison precedes gain');
check(order.indexOf('fa-qualifier')<order.indexOf('fa-pccr-result'),'Conclusion precedes comparison');
check(app.$('fa-gain-breakdown').closest('details')!==null,'Secondary percentages are in the explanation');
app=render({ref:'F',paidClass:'2'});
check(text(app,'fa-result-heading')==='Não identificamos diferença neste cenário.','Matching positions are not presented as a pending entitlement');
check(app.$('fa-retro').hidden&&app.$('fa-gain').hidden,'No generic arrears or gain pitch for a fully matching modern case');
check(text(app,'fa-gain-value')==='0,00%','Zero remains a numeric result for the recorded comparison');
check(text(app,'fa-qualifier').includes('não confirma os valores'),'Matching positions do not validate payroll');
app=render({continuous:false});
check(app.$('fa-gain').hidden&&app.$('fa-gain-numbers').hidden,'Incomplete conditions are not converted to zero gain');
check(text(app,'fa-result-note').includes('avaliações')&&text(app,'fa-result-note').includes('ficha funcional'),'Specific evidence is requested');
app=render({titleValid:'unknown'});
check(text(app,'fa-vertical').startsWith('Possível'),'Title uncertainty survives the clearer presentation');
check(text(app,'fa-gain-note').includes('condicionais'),'A conditional gain is labeled conditional');
check(text(app,'fa-result-note').includes('360 horas'),'Title requirements are actionable');
const legacy=cases[0].input;
app=render({},legacy);
check(text(app,'fa-result-heading')==='Encontramos avanços para conferir.','Legacy phase has a positive but bounded conclusion');
check(text(app,'fa-old-target-percent').includes('24,5%')&&text(app,'fa-new-count')==='5 avanços','Historical results remain independent');
check(text(app,'fa-horizontal')==='Nível a confirmar','Five temporal advances are not converted into level F without an act');
check(app.$('fa-gain').hidden,'Legacy percentages are not silently added');
check(text(app,'fa-result-note').includes('ato de enquadramento')&&text(app,'fa-result-note').includes('folhas da época'),'Both missing documents are named');
app=render({anchorDate:'01/01/2020',anchorLevel:'D',ref:'F',oldPaidRef:'I'},legacy);
check(text(app,'fa-result-heading')==='No PCCR, as posições coincidem.','Matching PCCR positions do not erase a possible historical difference');
check(!app.$('fa-retro').hidden&&text(app,'fa-result-note').includes('avanços antigos'),'Old-regime review remains explicit');
app=render({status:'retired',careerEnd:''});
check(text(app,'fa-result-heading')==='Precisamos do histórico da carreira.','Unknown career end is not a no-right conclusion');
check(text(app,'fa-result-note').includes('aposentadoria'),'Missing retirement date is explained');
app=render({status:'retired',careerEnd:'01/01/2025'});
check(app.$('fa-gain').hidden&&text(app,'fa-result-note').includes('regra do benefício'),'Career projection does not become automatic benefit uplift');
app=render({status:'temporary'});
check(app.$('fa-pccr-result').hidden&&app.$('fa-retro').hidden,'Contract case avoids an irrelevant effective-career table');
check(text(app,'fa-result-note').includes('contrato'),'Contract review is the concrete next step');
app=render({ref:'L'});
check(app.$('fa-gain').hidden&&text(app,'fa-result-note').includes('não projetamos redução'),'Position above the temporal scenario is not reduced');
check(text(app,'fa-contact-next')==='Enviar para análise do meu caso →','Sending has an explicit purpose');
console.log(checks+' result presentation checks passed.');
